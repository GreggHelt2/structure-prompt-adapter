"""Opt-in bitwise-deterministic RFdiffusion3 inference.

WHY THIS EXISTS. RFD3 as shipped is not bitwise reproducible: a fixed seed reproduces the initial
noise cloud and the sampling distribution, but not the final structure. Two runs of one config at one
seed differ by roughly 0.5 to 0.8 Å aligned Cα typically, but the tail is what matters: of four
designs measured at one seed, three reproduced to about 0.6 Å and the fourth landed 7.15 Å away, which
is a different structure rather than a perturbed one. Every number this project
reports is therefore a rate or a mean over n, and every figure names a persisted coordinate file
rather than a re-runnable seed.

THE CAUSE IS ONE OP, not the reduced-precision path. Measured 2026-09-08 (dev ``plan/91`` §2):

- ``foundry/src/foundry/utils/torch.py`` ``scatter_mean()`` dispatches every non-MPS device to
  ``Tensor.index_reduce``, which accumulates with CUDA atomics, so the summation order varies run to
  run. On the A5000 it produced **50 distinct bit patterns in 50 identical calls**.
- It is reached from ``rfd3/model/layers/blocks.py`` ``LinearEmbedWithPool`` (atom features pooled
  into token features), instantiated once as ``RFD3_diffusion_module.process_a`` and invoked on the
  noised coordinates roughly 100 to 300 times per structure.
- **bf16 is NOT the cause.** bf16 GEMMs are bit-exact run to run (1 distinct bit pattern in 50, max
  abs Δ 0.000e+00). Reduced precision changes the rounding, not the order of summation. bf16 only
  *amplifies*, by about 65,000x: the same op spreads 2.3e-02 in bf16 against 3.6e-07 in fp32.

WHY THE TORCH FLAGS DO NOT WORK HERE, which is the trap this module exists to route around.
``torch.use_deterministic_algorithms(True)`` **raises** for ``index_reduce_cuda``, because PyTorch
ships no deterministic kernel for it, and with ``warn_only=True`` it warns and then runs the
nondeterministic kernel anyway. PyTorch *does* ship deterministic routes for ``scatter_add`` and
``index_add``; ``index_reduce`` is the odd one out, and there is no feature request to change that.
So a source-level replacement is the only route, and no determinism flags or environment variables
are needed once it is in place (verified: bit-identical with every flag off).

THIS IS NOT OUR DISCOVERY. The diagnosis is public and 7.5 months old: RosettaCommons/foundry issue
#170 named ``index_reduce``, this file and this function on 2026-01-22, and is still open. Nobody had
fixed it, upstream or in any of 179 forks. See dev ``plan/91`` §0.

⛔ WHAT THIS DOES NOT BUY. Enabling this **changes the numbers**. A deterministic run does not
reproduce anything generated by the stock build: same seed, deterministic against stock, gives
aligned Cα-RMSD 0.056 to 2.469 Å across 4 designs. It is a different draw from the same
distribution. This is a go-forward guarantee only, so every archived structure stays exactly as
recorded and any table mixing the two builds compares across two slightly different models.

⛔ AND THE GUARANTEE IS A TUPLE, NOT A SEED. Bit-identity holds for a fixed seed **and** the same
``num_designs`` (K) **and** the same GPU model **and** the same torch/CUDA build. K is part of the
identity and that is not fixable: design *i* at K=4 differs from K=8 by up to 2.433 Å, because the
batch dimension changes tensor shapes and therefore which GEMM kernel cuBLAS picks. You cannot
regenerate one design of an 8-design run by re-running it alone.
"""

from __future__ import annotations

from typing import Any

#: Set by :func:`enable_deterministic`, read by the provenance writer. Never patched at import.
_STATE: dict[str, Any] = {"enabled": False, "patched": []}


def deterministic_scatter_mean(zeros, dim, index, source):
    """Order-stable drop-in for ``foundry.utils.torch.scatter_mean``.

    ``index`` maps each atom to its token, so ``oh`` is the ``[tokens, atoms]`` membership matrix,
    ``oh @ source`` sums each token's atoms, and dividing by the row sums gives the mean. A token
    with no atoms yields 0, matching ``include_self=False`` against a zero-filled output. ``zeros``
    is used only for its shape, which is also true of the original (it does not mutate it).

    The point is that the reduction becomes a **GEMM**, and GEMMs are bit-exact run to run on fixed
    shapes. Measured against an fp64 reference this is also slightly *more* accurate than
    ``index_reduce`` (1.639e-07 against 2.065e-07 in fp32), and end to end it is cost-neutral
    (20.24 s against 20.39 s at L=100/K=4, overlapping ranges).

    ⚠️ SCALING, measured rather than reasoned about. This is O(tokens × atoms) in both memory and
    FLOPs, against O(atoms) for ``index_reduce``, so the FLOP ratio reaches ~2700x at complex scale.
    **That does not translate into wall-clock**, because tensor cores absorb it. Measured on the
    A5000 in bf16 at C=384, per call:

    ==========================  ======  ======  ==============  ==========  =======  ==========
    case                        tokens   atoms   index_reduce     one-hot     ratio   transient
    ==========================  ======  ======  ==============  ==========  =======  ==========
    L=100 monomer                  100     800        87.3 us     163.0 us    1.87x      0.2 MB
    L=215 multimer                 215    1720        90.1 us     163.2 us    1.81x      0.7 MB
    500-token complex              500    4000       147.4 us     167.4 us    1.14x      4.0 MB
    MCL1-scale                    1369   10201       309.2 us     517.7 us    1.67x     27.9 MB
    ==========================  ======  ======  ==============  ==========  =======  ==========

    Worst case is 209 us per call, which over the 100 to 300 calls per structure is 21 to 63 ms
    against a multi-minute generation at that size: under 0.1%. So the end-to-end cost-neutral result
    holds because this op is a small fraction of total time either way, NOT because the ratio is 1.
    If a system ever appears where it does matter, the O(atoms) alternative is a sorted
    ``segment_reduce`` or a padded ``[tokens, max_atoms_per_token, C]`` gather-and-sum, both equally
    deterministic. ⛔ Do NOT substitute a ``cumsum``-based segment reduce: it is deterministic but
    numerically far worse from cancellation (3.099e-06 fp32, 1.907e-01 bf16, measured).

    The technique is not novel and we should not claim it is: Boltz already pools atoms into tokens
    with exactly this dense one-hot ``bmm`` in production (``boltz/model/modules/encoders.py:533``),
    with no determinism intent stated anywhere in that repo.
    """
    import torch

    # The one call site (blocks.py:217) passes -2, the token axis, and this implementation assumes
    # it. Assert rather than silently doing the wrong thing if another call site ever appears.
    ndim = source.dim()
    if dim not in (-2, ndim - 2):
        raise NotImplementedError(
            f"deterministic_scatter_mean only implements the token axis (dim=-2), got dim={dim} "
            f"for a {ndim}-D source. See spa.eval.determinism."
        )

    n_tokens = zeros.shape[-2]
    n_atoms = index.shape[0]
    onehot = torch.zeros(n_tokens, n_atoms, device=source.device, dtype=source.dtype)
    onehot[index, torch.arange(n_atoms, device=source.device)] = 1.0
    counts = onehot.sum(-1, keepdim=True).clamp(min=1)
    return (onehot @ source) / counts


def enable_deterministic() -> dict[str, Any]:
    """Patch RFD3's atom-to-token pooling to be order-stable. Idempotent.

    ⛔ Must be called BEFORE the engine runs, and only when the caller has opted in. Nothing is
    patched at import, so a run with the toggle off is byte-identical to not having this module at
    all, in the same way SPA's λ=0 identity gate is exact rather than approximate.

    Both bindings are replaced. ``blocks.py:33`` does ``from foundry.utils.torch import
    scatter_mean``, so patching only the source module leaves the live call site pointing at the
    original: omitting the second patch silently does nothing.

    Note that ``scatter_mean`` is shared with ``rf3`` and ``rfd3na``. Patching it in-process is safe
    precisely because it is a runtime patch and not an edit to the read-only dependency repo: it
    affects only this process, and only when explicitly enabled.

    ⚠️ PINNED TO OUR CLONE'S CALL SHAPE. The ``scatter_mean`` wrapper arrived in foundry PR #260 (MPS
    support); before it, ``blocks.py`` called ``.index_reduce(`` **directly**. Measured across the
    diverged foundry forks, 22 of 34 still use that older shape, and ``rfd3na`` calls it directly
    today at ``rfd3na/model/layers/blocks.py:255``. Our pinned clone is post-#260 and goes through the
    wrapper, so patching ``scatter_mean`` is correct here, but on an older checkout this would patch
    nothing while reporting success. If the pin ever moves backwards, assert the wrapper exists
    rather than trusting it. Provenance records exactly which bindings were replaced for this reason.
    """
    if _STATE["enabled"]:
        return dict(_STATE)

    import foundry.utils.torch as foundry_torch
    import rfd3.model.layers.blocks as rfd3_blocks

    patched = []
    foundry_torch.scatter_mean = deterministic_scatter_mean
    patched.append("foundry.utils.torch.scatter_mean")
    # The from-import binding actually used at blocks.py:217. Patching only the line above is a
    # silent no-op for the live call site.
    rfd3_blocks.scatter_mean = deterministic_scatter_mean
    patched.append("rfd3.model.layers.blocks.scatter_mean")

    _STATE.update(enabled=True, patched=patched, replaced="Tensor.index_reduce", by="one-hot matmul")
    print(
        "[determinism] ENABLED: RFD3 atom-to-token pooling is now order-stable "
        f"({len(patched)} bindings patched). Outputs will NOT match stock-build runs at the same seed."
    )
    return dict(_STATE)


def state() -> dict[str, Any]:
    """What :func:`enable_deterministic` did, for the run's provenance record."""
    return dict(_STATE)


def maybe_enable(cfg) -> dict[str, Any]:
    """Enable iff ``eval.deterministic`` is truthy. The single decision point for the toggle."""
    try:
        wanted = bool(cfg.eval.get("deterministic", False))
    except Exception:
        wanted = False
    return enable_deterministic() if wanted else state()
